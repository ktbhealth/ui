#!/usr/bin/env bun
/**
 * Extract design tokens from src/globals.css into DTCG tokens.json
 * and a flat tokens.ts for non-CSS consumers.
 *
 * globals.css remains the single source of truth (Tailwind v4 needs it).
 * This script is the only bridge to other formats.
 *
 * Usage: bun run scripts/css-to-dtcg.ts
 */
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const css = readFileSync(join(root, "src/globals.css"), "utf8");

function varsOf(block: string): Record<string, string> {
	const out: Record<string, string> = {};
	for (const m of block.matchAll(/--([\w-]+):\s*([^;]+);/g)) {
		out[m[1]] = m[2].trim();
	}
	return out;
}

const lightBlock = css.match(/:root\s*\{([\s\S]*?)\n\}/)?.[1];
const darkBlock = css.match(/\.dark\s*\{([\s\S]*?)\n\}/)?.[1];
if (!lightBlock) throw new Error(":root block not found in globals.css");

const light = varsOf(lightBlock);
const dark = darkBlock ? varsOf(darkBlock) : {};

function typeOf(name: string): string {
	if (name.startsWith("shadow")) return "string";
	if (name === "radius") return "dimension";
	return "color";
}

const groups: Record<string, Record<string, unknown>> = {};
const flatLight: Record<string, string> = {};
const flatDark: Record<string, string> = {};

for (const [name, value] of Object.entries(light)) {
	const key = name.replaceAll("-", "_");
	const entry: Record<string, unknown> = { $value: value, $type: typeOf(name) };
	if (name in dark) {
		entry.$extensions = { mode: { dark: dark[name] } };
		flatDark[name] = dark[name];
	}
	(groups.color ??= {})[key] = entry;
	flatLight[name] = value;
}

const tokensJson = { tokens: groups };
mkdirSync(join(root, "tokens"), { recursive: true });
writeFileSync(join(root, "tokens", "tokens.json"), JSON.stringify(tokensJson, null, "\t") + "\n");

const ts = `// Autogenerated by scripts/css-to-dtcg.ts. DO NOT EDIT.
// Source of truth: src/globals.css

export const tokensLight = ${JSON.stringify(flatLight, null, "\t")} as const;

export const tokensDark = ${JSON.stringify(flatDark, null, "\t")} as const;
`;
mkdirSync(join(root, "src/generated"), { recursive: true });
writeFileSync(join(root, "src/generated/tokens.ts"), ts);

console.log(`css-to-dtcg: ${Object.keys(light).length} tokens (${Object.keys(dark).length} dark overrides)`);
